<?php
$flexify_slider_sc = flexify_get_theme_option( 'front_page_title_shortcode' );
if ( ! empty( $flexify_slider_sc ) && strpos( $flexify_slider_sc, '[' ) !== false && strpos( $flexify_slider_sc, ']' ) !== false ) {

	?><div class="front_page_section front_page_section_title front_page_section_slider front_page_section_title_slider
		<?php
		if ( flexify_get_theme_option( 'front_page_title_stack' ) ) {
			echo ' sc_stack_section_on';
		}
		?>
	">
	<?php
		// Add anchor
		$flexify_anchor_icon = flexify_get_theme_option( 'front_page_title_anchor_icon' );
		$flexify_anchor_text = flexify_get_theme_option( 'front_page_title_anchor_text' );
	if ( ( ! empty( $flexify_anchor_icon ) || ! empty( $flexify_anchor_text ) ) && shortcode_exists( 'trx_sc_anchor' ) ) {
		echo do_shortcode(
			'[trx_sc_anchor id="front_page_section_title"'
									. ( ! empty( $flexify_anchor_icon ) ? ' icon="' . esc_attr( $flexify_anchor_icon ) . '"' : '' )
									. ( ! empty( $flexify_anchor_text ) ? ' title="' . esc_attr( $flexify_anchor_text ) . '"' : '' )
									. ']'
		);
	}
		// Show slider (or any other content, generated by shortcode)
		echo do_shortcode( $flexify_slider_sc );
	?>
	</div>
	<?php

} else {

	?>
	<div class="front_page_section front_page_section_title
		<?php
		$flexify_scheme = flexify_get_theme_option( 'front_page_title_scheme' );
		if ( ! empty( $flexify_scheme ) && ! flexify_is_inherit( $flexify_scheme ) ) {
			echo ' scheme_' . esc_attr( $flexify_scheme );
		}
		echo ' front_page_section_paddings_' . esc_attr( flexify_get_theme_option( 'front_page_title_paddings' ) );
		if ( flexify_get_theme_option( 'front_page_title_stack' ) ) {
			echo ' sc_stack_section_on';
		}
		?>
		"
		<?php
		$flexify_css      = '';
		$flexify_bg_image = flexify_get_theme_option( 'front_page_title_bg_image' );
		if ( ! empty( $flexify_bg_image ) ) {
			$flexify_css .= 'background-image: url(' . esc_url( flexify_get_attachment_url( $flexify_bg_image ) ) . ');';
		}
		if ( ! empty( $flexify_css ) ) {
			echo ' style="' . esc_attr( $flexify_css ) . '"';
		}
		?>
	>
	<?php
		// Add anchor
		$flexify_anchor_icon = flexify_get_theme_option( 'front_page_title_anchor_icon' );
		$flexify_anchor_text = flexify_get_theme_option( 'front_page_title_anchor_text' );
	if ( ( ! empty( $flexify_anchor_icon ) || ! empty( $flexify_anchor_text ) ) && shortcode_exists( 'trx_sc_anchor' ) ) {
		echo do_shortcode(
			'[trx_sc_anchor id="front_page_section_title"'
									. ( ! empty( $flexify_anchor_icon ) ? ' icon="' . esc_attr( $flexify_anchor_icon ) . '"' : '' )
									. ( ! empty( $flexify_anchor_text ) ? ' title="' . esc_attr( $flexify_anchor_text ) . '"' : '' )
									. ']'
		);
	}
	?>
		<div class="front_page_section_inner front_page_section_title_inner
		<?php
		if ( flexify_get_theme_option( 'front_page_title_fullheight' ) ) {
			echo ' flexify-full-height sc_layouts_flex sc_layouts_columns_middle';
		}
		?>
			"
			<?php
			$flexify_css      = '';
			$flexify_bg_mask  = flexify_get_theme_option( 'front_page_title_bg_mask' );
			$flexify_bg_color_type = flexify_get_theme_option( 'front_page_title_bg_color_type' );
			if ( 'custom' == $flexify_bg_color_type ) {
				$flexify_bg_color = flexify_get_theme_option( 'front_page_title_bg_color' );
			} elseif ( 'scheme_bg_color' == $flexify_bg_color_type ) {
				$flexify_bg_color = flexify_get_scheme_color( 'bg_color', $flexify_scheme );
			} else {
				$flexify_bg_color = '';
			}
			if ( ! empty( $flexify_bg_color ) && $flexify_bg_mask > 0 ) {
				$flexify_css .= 'background-color: ' . esc_attr(
					1 == $flexify_bg_mask ? $flexify_bg_color : flexify_hex2rgba( $flexify_bg_color, $flexify_bg_mask )
				) . ';';
			}
			if ( ! empty( $flexify_css ) ) {
				echo ' style="' . esc_attr( $flexify_css ) . '"';
			}
			?>
		>
			<div class="front_page_section_content_wrap front_page_section_title_content_wrap flexify_content_wrap">
				<?php
				// Caption
				$flexify_caption = flexify_get_theme_option( 'front_page_title_caption' );
				if ( ! empty( $flexify_caption ) || ( current_user_can( 'edit_theme_options' ) && is_customize_preview() ) ) {
					?>
					<h1 class="front_page_section_caption front_page_section_title_caption front_page_block_<?php echo ! empty( $flexify_caption ) ? 'filled' : 'empty'; ?>"><?php echo wp_kses( $flexify_caption, 'flexify_kses_content' ); ?></h1>
					<?php
				}

				// Description (text)
				$flexify_description = flexify_get_theme_option( 'front_page_title_description' );
				if ( ! empty( $flexify_description ) || ( current_user_can( 'edit_theme_options' ) && is_customize_preview() ) ) {
					?>
					<div class="front_page_section_description front_page_section_title_description front_page_block_<?php echo ! empty( $flexify_description ) ? 'filled' : 'empty'; ?>"><?php echo wp_kses( wpautop( $flexify_description ), 'flexify_kses_content' ); ?></div>
					<?php
				}

				// Buttons
				if ( flexify_get_theme_option( 'front_page_title_button1_link' ) != '' || flexify_get_theme_option( 'front_page_title_button2_link' ) != '' ) {
					?>
					<div class="front_page_section_buttons front_page_section_title_buttons">
					<?php
						flexify_show_layout( flexify_customizer_partial_refresh_front_page_title_button1_link() );
						flexify_show_layout( flexify_customizer_partial_refresh_front_page_title_button2_link() );
					?>
					</div>
					<?php
				}
				?>
			</div>
		</div>
	</div>
	<?php
}
